import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { spawn } from 'node:child_process';
import dotenv from 'dotenv';
import mongoose from 'mongoose';
import { assertIsolatedTestDatabase } from '../test/helpers/testIsolation.js';

const config = fs.existsSync('.env') ? dotenv.parse(fs.readFileSync('.env')) : {};
const source = process.env.TEST_MONGO_URI || process.env.MONGO_URI || config.MONGO_URI;
if (!source) throw new Error('No MongoDB connection configured.');
let uri;
try { uri = new URL(source); } catch { throw new Error('MongoDB URI could not be parsed; its contents are not printed.'); }
const runId = crypto.randomBytes(12).toString('hex');
uri.pathname = `/pfem_us29_test_${runId}`;
const name = assertIsolatedTestDatabase(uri.href, runId);
const connection = await mongoose.createConnection(uri.href, { serverSelectionTimeoutMS: 5000 }).asPromise();
// A name generated by this invocation must not already hold data, even if empty.
const databases = await connection.db.admin().listDatabases({ nameOnly: true });
if (databases.databases.some((db) => db.name === name)) throw new Error('Generated test database already exists; refusing to reset it.');
await connection.db.collection('__test_run').insertOne({ runId, createdAt: new Date() });
await connection.close();
const artifacts = fs.mkdtempSync(path.join(os.tmpdir(), 'pfem-us29-tests-'));
console.log(`Verified fresh isolated database: ${name}; artifacts: ${artifacts}`);
const files = process.argv.slice(2);
const selected = files.length ? files : fs.readdirSync('test').filter((f) => f.endsWith('.integration.test.js')).map((f) => `test/${f}`);
const child = spawn(process.execPath, ['--test', '--test-concurrency=1', ...selected], {
  stdio: 'inherit',
  env: { ...process.env, NODE_ENV: 'test', SMTP_HOST: '', SMTP_USER: '', SMTP_PASS: '', SMTP_FROM: '', TEST_MONGO_URI: uri.href, PFEM_TEST_RUN_ID: runId,
    EMAIL_VERIFICATION_SECRET: crypto.randomBytes(48).toString('hex'),
    ENCRYPTION_KEY: crypto.randomBytes(32).toString('hex'), JWT_SECRET: crypto.randomBytes(48).toString('hex'),
    BACKUP_ENCRYPTION_KEY: crypto.randomBytes(32).toString('hex'), BACKUP_DIR: path.join(artifacts, 'backups'),
    UPLOAD_DIR: path.join(artifacts, 'uploads'), SCHEDULER_ENABLED: 'false' },
});
child.on('exit', (code) => { console.log(`Isolated database retained for inspection: ${name}`); process.exitCode = code ?? 1; });
